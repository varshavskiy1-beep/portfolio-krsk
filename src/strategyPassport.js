export function authoredPassportIds() {
  return Object.keys(PASSPORTS);
}

export function hasAuthoredPassport(botId) {
  return Boolean(PASSPORTS[botId]);
}

export function getPassport(botId, fallbackLogic = "") {
  const authored = PASSPORTS[botId];
  if (authored) return { ...authored, authored: true };
  return stubPassport(botId, fallbackLogic);
}

/** bot_id, которые кабинет реально рисует: счета снимка + portal shells. */
export function displayedBotIds(accounts = []) {
  const ids = [];
  const seen = new Set();
  for (const a of mergePortalAccounts(accounts)) {
    if (!a?.bot_id || seen.has(a.bot_id)) continue;
    seen.add(a.bot_id);
    ids.push(a.bot_id);
  }
  return ids;
}

const UI_STRING_KEYS = ["title"];

function collectUiStrings(passport) {
  const out = [];
  out.push(passport.title);
  for (const p of passport.essence.paragraphs) out.push(p);
  for (const s of passport.decisionSteps) out.push(s);
  for (const row of passport.parameters) {
    out.push(row.name, row.value, row.meaning);
  }
  for (const p of passport.risk.paragraphs) out.push(p);
  for (const p of passport.risk.items) out.push(p);
  out.push(passport.testing.statusLabel, passport.testing.disclaimer);
  for (const m of passport.testing.missing) out.push(m);
  const book = passport.testing.backtest;
  if (book) {
    out.push(
      book.primaryTitle,
      book.referenceTitle,
      book.periodTitle,
      book.cagrDisclaimer,
      book.equityNote,
      book.paperNote,
      book.weakWindowNote,
      book.missingAfterPack,
    );
    for (const row of book.primaryMetrics || []) {
      out.push(row.name, row.value, row.meaning);
    }
    for (const w of [...(book.windowsLev3 || []), ...(book.windowsLev1 || [])]) {
      out.push(w.label_ru, w.period, w.cagr, w.maxDd, w.pf, w.trades, w.weak_note_ru);
    }
  }
  for (const g of GLOSSARY) {
    out.push(g.term, g.meaning);
  }
  return out.filter(Boolean);
}

export function passportUiStrings(botId) {
  return collectUiStrings(getPassport(botId));
}

/**
 * Проверки паспорта: обязательные секции, unknown = «нет данных»,
 * в UI-строках нет слова seed, тест без walk-forward без данных.
 */
export function validatePassport(passport) {
  const errors = [];
  if (!passport?.botId) errors.push("нет botId");
  if (!passport?.title) errors.push("нет title");
  if (!passport.essence?.paragraphs?.length) errors.push("пустая суть");
  if (!passport.decisionSteps?.length) errors.push("нет шагов решения");
  if (!passport.parameters?.length) errors.push("нет таблицы параметров");
  if (!passport.risk?.paragraphs?.length) errors.push("нет блока риска");
  if (!passport.testing?.status) errors.push("нет статуса теста");

  for (const row of passport.parameters || []) {
    if (!row.known && row.value !== NO_DATA) {
      errors.push(`параметр «${row.name}»: неизвестное значение должно быть «${NO_DATA}»`);
    }
    if (row.known && (row.value == null || row.value === "")) {
      errors.push(`параметр «${row.name}»: пустое известное значение`);
    }
  }

  if (passport.testing?.walkForward) {
    errors.push("walkForward заполнен, но полной сетки walk-forward в репозитории нет");
  }
  if (passport.testing?.overlay) {
    errors.push("overlay (эталон кривой) заполнен, но файла equity/overlay нет");
  }
  if (passport.testing?.status === TEST_STATUS.NEEDS_DATA) {
    if (passport.testing.backtest) {
      errors.push("backtest заполнен при статусе needs_data");
    }
    if (passport.testing.statusLabel !== TEST_STATUS_LABEL[TEST_STATUS.NEEDS_DATA]) {
      errors.push("неверная подпись статуса «Нужны данные для проверки»");
    }
    if (!passport.testing.missing?.length) {
      errors.push("при статусе needs_data список недостающего пуст");
    }
  }
  if (passport.testing?.status === TEST_STATUS.HAS_BOOK) {
    const book = passport.testing.backtest;
    if (!book) errors.push("has_book без блока backtest");
    if (!passport.testing.asof) errors.push("has_book без даты книги");
    if (!book?.primaryMetrics?.length) errors.push("has_book без метрик главной карточки");
    if (!book?.windowsLev3?.length) errors.push("has_book без окон 3×");
    if (!passport.testing.missing?.length) {
      errors.push("при статусе has_book список оставшихся пробелов пуст");
    }
    for (const row of book?.primaryMetrics || []) {
      if (!row.known && row.value !== NO_DATA) {
        errors.push(`метрика «${row.name}»: неизвестное значение должно быть «${NO_DATA}»`);
      }
      if (row.known && (row.value == null || row.value === "")) {
        errors.push(`метрика «${row.name}»: пустое известное значение`);
      }
    }
  }

  for (const s of collectUiStrings(passport)) {
    if (/\bseed\b/i.test(s)) errors.push(`в UI-строке есть seed: ${s.slice(0, 80)}`);
  }

  return errors;
}

export function validateDisplayedPassports(accounts = []) {
  const report = [];
  for (const botId of displayedBotIds(accounts)) {
    const passport = getPassport(botId);
    const errors = validatePassport(passport);
    if (!hasAuthoredPassport(botId)) {
      errors.push("нет авторского паспорта для отображаемой стратегии");
    }
    report.push({ botId, ok: errors.length === 0, errors });
  }
  return report;
}

