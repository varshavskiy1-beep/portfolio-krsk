function formatRu(n, digits = 1) {
  if (n == null || Number.isNaN(Number(n))) return null;
  return new Intl.NumberFormat("ru-RU", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(Number(n));
}

function pct(n, digits = 1) {
  const s = formatRu(n, digits);
  return s == null ? null : `${s}%`;
}

function windowBounds(w) {
  if (!w.window_start && !w.window_end) return "вся история (границ в эталоне нет)";
  return `${w.window_start} — ${w.window_end}`;
}

function displayWindow(w, noData) {
  return {
    id: w.id,
    label: w.label,
    label_ru: w.label_ru,
    role: w.role,
    leverage: w.leverage,
    period: windowBounds(w),
    years: w.years_est == null ? noData : `≈ ${formatRu(w.years_est, 2)} года`,
    cagr: pct(w.cagr_pct, 1) || noData,
    maxDd: pct(w.max_dd_pct, 1) || noData,
    pf: formatRu(w.profit_factor, 3) || noData,
    mar: w.mar == null ? noData : formatRu(w.mar, 2),
    trades: w.n_trades == null ? noData : String(w.n_trades),
    sharpe: w.sharpe == null ? noData : formatRu(w.sharpe, 2),
    winrate: w.winrate == null ? noData : pct(w.winrate * 100, 1),
    vol: w.vol_ann == null ? noData : formatRu(w.vol_ann, 2),
    weak: Boolean(w.weak),
    weak_note_ru: w.weak_note_ru || null,
  };
}

